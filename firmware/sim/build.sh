#!/usr/bin/env bash
# Build the host simulator against the firmware tree AS IT IS NOW (nothing is copied out of it).
#
#   ./build.sh                 → out/sim
#   FW=/path/to/firmware ./build.sh
#   SANITIZE=1 ./build.sh      → with -fsanitize=address,undefined
#
# Compiles the real ui_habitat.c, cable_client.c and app_main.c (each pulled into a wrapper TU so the
# driver can reach its statics), the real habitat renderer and its helpers, and cJSON 1.7.18 (the copy
# ESP-IDF v5.5 ships, in third_party/). The build flags match a production image: HABITAT_FOCUS_ONLY=1
# HABITAT_NO_COMPANION_ART=1 (main/CMakeLists.txt without DEVICE_ALL_SKINS).
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FW="${FW:?set FW to a patched openharness devices/harness-device/firmware (scripts/test-firmware.sh does this)}"
M="$FW/main"; H="$M/ui/habitat"
out="$here/out"; gen="$out/gen"
mkdir -p "$out" "$gen"

# The view and action names, read from the enums in ui_habitat.c so `view`/`hits` stay right when the
# firmware adds a screen.
python3 -I - "$H/ui_habitat.c" "$gen/sim_names.inc" <<'PY'
import re, sys
src = open(sys.argv[1], encoding="utf-8").read()
def names(typename):
    m = re.search(r"typedef enum \{([^{}]*)\}\s*" + typename + r";", src, re.S)
    assert m, typename
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    out = []
    for tok in body.split(","):
        tok = tok.strip()
        if not tok: continue
        assert "=" not in tok, "explicit enum values are not handled: " + tok
        out.append(tok)
    return out
with open(sys.argv[2], "w") as f:
    f.write("// generated by build.sh from ui_habitat.c\n")
    f.write("static const char *const sim_view_names[] = {%s};\n" % ", ".join('"%s"' % n for n in names("view_t")))
    f.write("static const char *const sim_action_names[] = {%s};\n" % ", ".join('"%s"' % n for n in names("action_kind_t")))
PY

version="$(tr -d '\n' < "$FW/version.txt" 2>/dev/null || echo 0.0.0)"
CFLAGS=(-std=gnu11 -O1 -g -Wall -Wno-format-truncation -Wno-unused-function -Wno-unused-variable
        -Wno-unused-but-set-variable -Wno-missing-braces
        -DHABITAT_FOCUS_ONLY=1 -DHABITAT_NO_COMPANION_ART=1 "-DSIM_FW_VERSION=\"$version\"")
if [[ -n "${SANITIZE:-}" ]]; then CFLAGS+=(-fsanitize=address,undefined -fno-omit-frame-pointer); fi
INC=(-I "$here/stubs/include" -I "$here/src" -I "$gen" -I "$M" -I "$M/ui" -I "$H" -I "$M/board"
     -I "$here/third_party/cJSON")

SRCS=(
  "$here/src/sim.c" "$here/src/sim_platform.c" "$here/src/sim_device.c"
  "$here/src/sim_ui.c"      # includes $H/ui_habitat.c
  "$here/src/sim_cable.c"   # includes $M/cable_client.c
  "$here/src/sim_app.c"     # includes $M/app_main.c
  "$M/cable_json_guard.c" "$M/cable_machines.c" "$M/cable_scroll.c" "$M/cable_features.c" "$M/pet_store.c"
  "$H/terminal.c" "$H/scroll.c" "$H/workspace.c" "$H/selection.c" "$H/carry.c" "$H/visit.c" "$H/form.c"
  "$H/draft.c" "$H/gestures.c" "$H/tim.c" "$H/character.c" "$H/illustrated.c" "$H/illustrated_cache.c"
  "$H/character_motion.c" "$H/character_layout.c" "$H/tux.c" "$H/focus.c" "$H/octopus.c" "$H/ascii_clip.c"
  "$H/octopus_font.c" "$H/command_face.c" "$H/fonts.c" "$H/lvgl_fonts.c" "$H/lvgl_icons.c" "$H/focus_marks.c"
  "$H/focus_faces.c" "$H/pb_faces.c" "$H/pets.c"
  "$here/third_party/cJSON/cJSON.c"
)
objs=(); pids=()
for src in "${SRCS[@]}"; do
  obj="$out/obj/$(basename "$(dirname "$src")")_$(basename "${src%.c}").o"
  mkdir -p "$out/obj"
  cc "${CFLAGS[@]}" "${INC[@]}" -c "$src" -o "$obj" &
  objs+=("$obj"); pids+=($!)
done
status=0
for pid in "${pids[@]}"; do wait "$pid" || status=1; done
[[ $status -eq 0 ]] || { echo "compile failed" >&2; exit 1; }
cc "${CFLAGS[@]}" -o "$out/sim" "${objs[@]}" -lz -lm
echo "built $out/sim (firmware $version from $FW)"
